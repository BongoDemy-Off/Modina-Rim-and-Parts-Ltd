import { ArrowLeft } from 'lucide-react';
import { Link, useParams } from 'react-router-dom';
import type { ReactNode } from 'react';
import { GovernanceNotice } from '../../components/governance/GovernanceNotice';
import { demoActivityEntries } from '../../data/activity-log';
import { demoAdminUsers } from '../../data/admin-users';
import { adminButtonClass } from '../../ui/Button';
import { SectionCard } from '../../ui/Card';
import { EmptyState } from '../../ui/FeedbackStates';
import { PageHeader } from '../../ui/PageHeader';
import { StatusBadge } from '../../ui/StatusBadge';

function Detail({ label, children }: { label: string; children: ReactNode }) {
  return <div className="min-w-0 rounded-lg border border-[var(--admin-border)] bg-slate-50 p-3"><dt className="text-xs font-extrabold uppercase tracking-wide text-[var(--admin-muted)]">{label}</dt><dd className="mt-1 break-words text-sm font-semibold text-[var(--admin-heading)]">{children}</dd></div>;
}

export default function ActivityLogDetail() {
  const { id } = useParams();
  const entry = demoActivityEntries.find((candidate) => candidate.id === id);
  if (!entry) return <EmptyState headingLevel={1} title="Activity Entry Not Found" description="This demo Activity Log ID does not exist." action={<Link to="/admin/activity-log" className={adminButtonClass('secondary')}><ArrowLeft className="h-4 w-4" aria-hidden="true" /> Back to Activity Log</Link>} />;
  const actor = demoAdminUsers.find((user) => user.id === entry.actorUserId);
  return (
    <div className="space-y-6 xl:space-y-8">
      <PageHeader eyebrow={`Activity Log UI prototype · ${entry.id}`} title={entry.actionType} description="Read-only synthetic demonstration entry. This is not evidence that an action actually occurred." actions={<Link to="/admin/activity-log" className={adminButtonClass('secondary')}><ArrowLeft className="h-4 w-4" aria-hidden="true" /> Back to Activity Log</Link>} />
      <GovernanceNotice tone="warning"><strong>Synthetic demonstration entry — no real audit storage exists.</strong> This record was seeded for UI review and was not generated by a prototype action.</GovernanceNotice>
      <SectionCard title="Activity detail" description="Read-only presentation; no edit, delete, replay, rollback, export, IP, device, location, session, or raw-payload data exists.">
        <dl className="grid min-w-0 gap-3 p-4 sm:grid-cols-2 sm:p-5">
          <Detail label="Demo Admin User">{actor?.displayName ?? 'Missing Demo User'}<span className="mt-1 block break-all text-xs font-normal text-[var(--admin-muted)]">Synthetic user ID: {entry.actorUserId}</span></Detail>
          <Detail label="Demo timestamp"><time>{entry.occurredAt}</time></Detail>
          <Detail label="Action">{entry.actionType}</Detail>
          <Detail label="Implemented Admin module">{entry.moduleLabel}</Detail>
          <Detail label="Target">{entry.targetLabel}</Detail>
          <Detail label="Target reference"><span className="break-all">{entry.targetReference}</span></Detail>
          <Detail label="Synthetic result"><StatusBadge status={entry.result} /></Detail>
          <Detail label="Source">Synthetic demonstration seed</Detail>
          <div className="sm:col-span-2"><Detail label="Summary">{entry.summary}</Detail></div>
        </dl>
      </SectionCard>
      <GovernanceNotice><strong>Read-only in this demo UI.</strong> No claim of immutability, compliance, legal admissibility, tamper resistance, or security-event logging is made.</GovernanceNotice>
    </div>
  );
}
